// Pre-build word to cluster map for O(1) synonym expansion
const SYNONYM_MAP: Map<string, string[]> = new Map();

for (const cluster of SYNONYM_CLUSTERS) {
  for (const word of cluster) {
    const norm = word.trim().toLowerCase();
    const existing = SYNONYM_MAP.get(norm) || [];
    const merged = Array.from(new Set([...existing, ...cluster]));
    SYNONYM_MAP.set(norm, merged);
  }
}

/**
 * Retrieves all synonyms and orthographic variants for a given Bengali token.
 */
export function getSynonymsAndVariants(token: string): string[] {
  if (!token) return [];
  const clean = token.trim().toLowerCase();
  return SYNONYM_MAP.get(clean) || [token];
}

/**
 * Checks whether a word is an explicit ablution variant
 */
export function isAblutionTerm(term: string): boolean {
  return ['ওযু', 'অজু', 'উযু', 'উজু', 'ওজু', 'ওযূ', 'উযূ'].includes(term.trim().toLowerCase());
}
